export const packages: UserAppPackage[] = PACKAGE_SEED.map((p, i) => {
  const testIds = pickMany(
    tests.map((t) => t.id),
    Math.min(p.count, tests.length),
  );
  const sumOfTests = testIds.reduce(
    (sum, id) => sum + (tests.find((t) => t.id === id)?.price ?? 0),
    0,
  );
  const price = Math.round(sumOfTests * 0.68);
  return {
    id: `package-${i + 1}`,
    name: p.name,
    testIds,
    price,
    sumOfTests,
    description: p.desc,
    active: randBool(0.92),
    orderCount: randInt(60, 2600),
  };
});
